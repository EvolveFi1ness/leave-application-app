(async () => {
  const id = new URLSearchParams(location.search).get('id');
  if (!id) { document.getElementById('doc').textContent = 'Missing id'; return; }
  try {
    const { app: a, settings: s } = await Api.get('/api/leaves/' + id + '/print-data');
    document.getElementById('st').textContent = `#${a.id} • ${a.status}`;
    const ex = a.extra_details || {};
    document.getElementById('doc').innerHTML = `
    <div style="text-align:center"><b>Republic of the Philippines</b><br><b>APPLICATION FOR LEAVE</b><br><span class="muted">${esc(s.office || '')} — ${esc(s.org_name || '')}</span></div>
    <table class="ph-t" style="margin-top:12px">
    <tr><td>Office / Department<br><b>${esc(a.department)}</b></td><td>Name<br><b>${esc(a.employee_name)}</b></td><td>Date of Filing<br><b>${esc((a.submitted_at || '').slice(0, 10))}</b></td></tr>
    <tr><td>Position<br><b>${esc(a.position)}</b></td><td colspan="2">Salary<br><b>${s.salary_visible === '1' ? '(on file)' : '—'}</b></td></tr>
    </table>
    <table class="ph-t"><tr><th colspan="2">TYPE OF LEAVE</th></tr>
    <tr><td><b>${esc(a.leave_name)}</b></td><td>Details: ${esc(JSON.stringify(ex))}</td></tr></table>
    <table class="ph-t"><tr><td>Number of working days<br><b>${a.working_days}</b></td><td>Inclusive dates<br><b>${esc(a.start_date)} → ${esc(a.end_date)}</b></td></tr>
    <tr><td colspan="2">Reason<br>${esc(a.reason)}</td></tr>
    <tr><td colspan="2">Emergency contact<br><b>${esc(a.emergency_name)} (${esc(a.emergency_relationship)}) ${esc(a.emergency_phone)}</b></td></tr></table>
    <table class="ph-t"><tr><th>Leave Credits Certification</th><th>Recommendation / Approval</th></tr>
    <tr><td>Status: <b>${a.status}</b></td><td>HR / Supervisor / Final Approver signatures: ______________</td></tr></table>
    <div class="muted" style="margin-top:8px">Generated by ${esc(s.org_name || 'Leave Management System')} • Print or Save as PDF from the browser dialog.</div>`;
  } catch (e) { document.getElementById('doc').innerHTML = `<div class="err">${esc(e.message)}</div>`; }
})();
